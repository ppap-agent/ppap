BEGIN;

-- Checker optimization and in-product checker generation are retired: customer
-- rules get checker programs prepared offline by the platform. Open optimizer
-- work stops; finished jobs stay in engine.jobs as history.
DROP TRIGGER IF EXISTS retire_checker_member ON product.memberships;
DROP TRIGGER IF EXISTS retire_checker_user ON product.users;
DROP FUNCTION IF EXISTS product.retire_checker_operator();
DROP FUNCTION IF EXISTS product.retire_checker_optimizations(uuid, uuid);
DROP INDEX IF EXISTS engine.optimization_notification_intent;
UPDATE engine.attempts a SET finished_at = clock_timestamp(), outcome = 'cancelled',
    diagnostic = a.diagnostic || '{"failure":"checker_optimization_retired"}'::jsonb
FROM engine.jobs j
WHERE a.job_id = j.id AND a.finished_at IS NULL AND j.status IN ('queued', 'leased')
  AND (j.kind = 'checker_optimization' OR (j.kind = 'feishu_notification' AND j.payload->>'stage' = 'optimization_completed'));
UPDATE engine.jobs SET status = 'cancelled', lease_until = NULL, updated_at = clock_timestamp(),
    result = COALESCE(result, '{}'::jsonb) || '{"failure":"checker_optimization_retired"}'::jsonb
WHERE status IN ('queued', 'leased')
  AND (kind = 'checker_optimization' OR (kind = 'feishu_notification' AND payload->>'stage' = 'optimization_completed'));
DROP TABLE IF EXISTS product.checker_feedback;
DROP TABLE IF EXISTS product.checker_optimizations;

-- Deep mode is a task choice, editable until acceptance and frozen on the Round.
-- A re-audit Task starts with it off.
ALTER TABLE product.audit_drafts ADD COLUMN IF NOT EXISTS deep_mode boolean NOT NULL DEFAULT false;
ALTER TABLE product.audit_rounds ADD COLUMN IF NOT EXISTS deep_mode boolean NOT NULL DEFAULT false;
GRANT SELECT (deep_mode) ON product.audit_drafts TO ppap_worker;

-- The program a deep-mode Round wrote for one target, per result attempt. The
-- Suite revision holds the exact generated bytes; it is never published.
-- (Not named checker_round_artifacts: 0070 drops that name on every apply.)
CREATE TABLE IF NOT EXISTS product.deep_round_programs (
    round_id uuid NOT NULL,
    file_version_id uuid NOT NULL,
    result_attempt integer NOT NULL CHECK (result_attempt > 0),
    tenant_id uuid NOT NULL REFERENCES product.tenants(id),
    suite_revision_id uuid NOT NULL REFERENCES product.suite_revisions(id),
    program_digest text NOT NULL CHECK (program_digest ~ '^[a-f0-9]{64}$'),
    input_digest text NOT NULL CHECK (input_digest ~ '^[a-f0-9]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (round_id, file_version_id, result_attempt),
    FOREIGN KEY (round_id, file_version_id) REFERENCES product.round_inputs(round_id, file_version_id)
);
GRANT SELECT, INSERT ON product.deep_round_programs TO ppap_worker;
GRANT SELECT ON product.deep_round_programs TO ppap_api;

-- Billing: acceptance records 500 points per target file ('audit'). A file whose
-- deep result is committed adds one 250-point 'deep_surcharge'; a file that fell
-- back to its Suite program is billed 500 only. The worker records the surcharge
-- in the same transaction that commits the result.
ALTER TABLE product.usage_events ADD COLUMN IF NOT EXISTS charge text NOT NULL DEFAULT 'audit';
ALTER TABLE product.usage_events DROP CONSTRAINT IF EXISTS usage_charge_known;
ALTER TABLE product.usage_events ADD CONSTRAINT usage_charge_known
    CHECK (charge IN ('audit', 'deep_surcharge') AND (charge = 'audit' OR file_version_id IS NOT NULL));
-- Same index name as 0027, so re-applying 0027 (IF NOT EXISTS) keeps this definition.
DROP INDEX IF EXISTS product.usage_events_file_slice_idx;
CREATE UNIQUE INDEX usage_events_file_slice_idx
    ON product.usage_events(round_id, file_version_id, charge, is_free_trial) WHERE file_version_id IS NOT NULL;
GRANT SELECT, INSERT ON product.usage_events TO ppap_worker;
GRANT SELECT (id, provider, external_key) ON product.tenants TO ppap_worker;
GRANT SELECT ON product.trial_cutover_baselines TO ppap_worker;

INSERT INTO product.schema_migrations (version) VALUES ('0072_deep_mode.sql') ON CONFLICT DO NOTHING;
COMMIT;
