CREATE SCHEMA IF NOT EXISTS product;
CREATE SCHEMA IF NOT EXISTS engine;

REVOKE ALL ON SCHEMA public FROM PUBLIC;

GRANT USAGE ON SCHEMA product TO ppap_api;
GRANT USAGE ON SCHEMA engine TO ppap_api;
GRANT USAGE ON SCHEMA engine TO ppap_worker;

ALTER DEFAULT PRIVILEGES IN SCHEMA product GRANT SELECT, INSERT, UPDATE ON TABLES TO ppap_api;
ALTER DEFAULT PRIVILEGES IN SCHEMA engine GRANT SELECT, INSERT ON TABLES TO ppap_api;
ALTER DEFAULT PRIVILEGES IN SCHEMA engine GRANT SELECT, INSERT, UPDATE ON TABLES TO ppap_worker;
ALTER DEFAULT PRIVILEGES IN SCHEMA engine GRANT USAGE, SELECT ON SEQUENCES TO ppap_api;
ALTER DEFAULT PRIVILEGES IN SCHEMA engine GRANT USAGE, SELECT ON SEQUENCES TO ppap_worker;

CREATE TABLE IF NOT EXISTS product.schema_migrations (
    version text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON product.schema_migrations TO ppap_api;

INSERT INTO product.schema_migrations (version) VALUES ('0001_schemas.sql')
ON CONFLICT DO NOTHING;
