import {test, expect} from '@playwright/test'
import {isolatedDevLogin, RULE_A, uploadBuffer, waitForRound} from './helpers'

test.describe.configure({mode: 'serial'})

test('submit, leave, return, review, and resubmit against isolated-dev', async ({page, request}) => {
  await page.setViewportSize({width: 390, height: 844})
  await isolatedDevLogin(page)
  await page.getByTestId('source-upload').setInputFiles(uploadBuffer('report.xlsx', 'browser-target-v1'))
  await page.waitForSelector('[data-testid="draft-items"]')
  await page.getByTestId('item-rule').first.selectOption(RULE_A)
  await page.getByTestId('source-upload').setInputFiles(uploadBuffer('context.pdf', 'browser-reference', 'application/pdf'))
  await page.waitForFunction(() => document.querySelector('[data-testid="draft-items"]')?.textContent?.includes('context.pdf'))
  await page.getByRole('checkbox', {name: '参与审核：context.pdf'}).uncheck()
  await page.waitForFunction(() => new URL(window.location.href).searchParams.get('draft'))
  const save = page.getByTestId('save-draft')
  if (await save.isEnabled()) await save.click()
  await page.getByTestId('submit-audit').click()
  const roundId = await waitForRound(page)
  await page.goto('/')
  await expect(page.locator('#audit-preparation')).toBeVisible()
  await page.goto(`/?round=${roundId}`)
  await page.waitForSelector('[data-testid="result-summary"]')
  await page.getByRole('navigation', {name: '审核条款'}).locator('[aria-current="true"]').click()
  await expect(page.getByTestId('finding-status').first).toHaveAttribute('data-status', 'PASS')
  await expect(page.getByTestId('result-summary')).toContainText('通过')
  const originalTab = page.getByRole('tab', {name: '原件', exact: true})
  if (await originalTab.isVisible()) await originalTab.click()
  await expect(page.getByTestId('file-version-list')).toContainText('report.xlsx')
  await expect(page.getByTestId('file-version-list')).toContainText('context.pdf')
  const original = page.getByTestId('open-original')
  const gap = page.getByTestId('locator-gap')
  if (await original.count() === 0) {
    await expect(gap).toBeVisible()
  } else {
    const href = await original.getAttribute('href')
    expect(href).toBeTruthy()
    const downloaded = await request.get(href!)
    expect(downloaded.status()).toBe(200)
    expect(await downloaded.body()).toEqual(Buffer.from('browser-target-v1'))
    await expect(page.getByTestId('file-preview')).toBeVisible()
    await expect(page.getByTestId('file-preview-name')).toContainText('report.xlsx')
    await page.getByRole('tab', {name: '检查与复核'}).click()
  }
  await expect(page.getByTestId('finding-heading').first).toBeVisible()
  await expect(page.getByTestId('finding-evidence').first).toBeVisible()
  await expect(page.getByTestId('nav-audit-files').last).toBeVisible()
  expect(await page.locator('h1').count()).toBe(1)
  await page.getByRole('tab', {name: '其他'}).click()
  await page.getByTestId('review-judgment').focus()
  expect(await page.evaluate(() => document.activeElement?.getAttribute('data-testid'))).toBe('review-judgment')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.activeElement?.getAttribute('data-testid'))).toBe('review-rationale')
  const nextFinding = page.getByRole('button', {name: '下一检查项'})
  await expect(nextFinding).toBeVisible()
  if (await nextFinding.isEnabled()) {
    await nextFinding.focus()
    expect(await page.evaluate(() => document.activeElement?.getAttribute('aria-label'))).toBe('下一检查项')
  }
  await page.getByTestId('review-judgment').fill('需修改')
  await page.getByTestId('review-rationale').fill('尺寸缺失')
  await page.getByTestId('review-next').fill('补传')
  const backToList = page.getByRole('button', {name: '← 检查项'})
  if (await backToList.isVisible()) await backToList.click()
  await page.getByRole('navigation', {name: '审核条款'}).locator('[aria-current="true"]').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByTestId('review-rationale')).toHaveValue('尺寸缺失')
  await expect(page.getByTestId('review-next')).toHaveValue('补传')
  await page.getByTestId('save-review').click()
  await page.waitForSelector('text=复核已保存')
  await page.getByTestId('prepare-again').click()
  await page.waitForSelector('#audit-preparation')
  await page.waitForSelector('[data-testid="submit-audit"]:not([disabled])')
  await page.getByTestId('source-upload').setInputFiles(uploadBuffer('report-v2.xlsx', 'browser-target-v2'))
  await page.waitForFunction(() => document.querySelector('[data-testid="draft-items"]')?.textContent?.includes('report-v2.xlsx'))
  await page.getByTestId('item-rule').last.selectOption(RULE_A)
  await page.getByTestId('submit-audit').click()
  await page.waitForSelector('[data-testid="previous-round"]')
  await expect(page.getByTestId('previous-round')).toBeVisible()
  await page.getByTestId('previous-round').click()
  await page.waitForSelector('[data-testid="review-judgment"]')
  await expect(page.getByTestId('review-judgment')).toHaveValue('需修改')
  await expect(page.getByTestId('nav-audit-files').last).toBeVisible()
  await expect(page.getByTestId('finding-heading').first).toBeVisible()
  await page.getByRole('tab', {name: '原件', exact: true}).click()
  await expect(page.getByTestId('file-version-list')).toContainText('report.xlsx')
  await page.locator('[data-ui="mobile-account"] [data-ui="account-button"]').click()
  await page.getByTestId('nav-usage').click()
  await page.waitForURL('**/usage')
  await page.waitForFunction(() => ['usage-list', 'usage-empty', 'usage-error'].some(id => Boolean(document.querySelector('[data-testid="' + id + '"]'))))
  const usageError = page.getByTestId('usage-error')
  if (await usageError.count() && await usageError.isVisible()) {
    throw new Error(await usageError.innerText())
  }
  await page.locator('.mobile-tab-bar [data-testid="nav-audit-files"]').click()
  await page.waitForURL('**/audit-files')
  await page.waitForFunction(() => ['history-list', 'history-empty', 'history-error'].some(id => Boolean(document.querySelector('[data-testid="' + id + '"]'))))
  const historyError = page.getByTestId('history-error')
  if (await historyError.count() && await historyError.isVisible()) {
    throw new Error(await historyError.innerText())
  }
  await expect(page.getByTestId('history-list')).toBeVisible()
  await expect(page.locator('[data-testid="history-result"]', {hasText: '通过'}).first).toBeVisible()
  await expect(page.getByTestId('history-version').first).not.toHaveText('')
})

test('docs-addon entry reports missing host', async ({page}) => {
  await page.setViewportSize({width: 560, height: 600})
  await page.goto('/addon')
  await page.waitForSelector('text=当前环境不支持 docs-addon 登录')
  await expect(page.getByTestId('addon-history')).toBeVisible()
  const href = await page.getByTestId('addon-history').getAttribute('href')
  expect(href && href.replace(/\/$/, '').endsWith('audit-files')).toBeTruthy()
  expect(href).not.toContain('.html')
  await expect(page.getByTestId('addon-submit')).toBeDisabled()
})

test('audit-files path loads history after login', async ({page}) => {
  await isolatedDevLogin(page)
  await page.getByTestId('pc-shell').getByTestId('nav-audit-files').click()
  await page.waitForURL('**/audit-files')
  await page.waitForFunction(() => ['history-list', 'history-empty', 'history-error'].some(id => Boolean(document.querySelector('[data-testid="' + id + '"]'))))
  const error = page.getByTestId('history-error')
  if (await error.count() && await error.isVisible()) {
    throw new Error(await error.innerText())
  }
  await expect(page.getByTestId('history-list').or(page.getByTestId('history-empty'))).toBeVisible()
  expect(page.url().replace(/\/$/, '').endsWith('/audit-files')).toBeTruthy()
})

test('return from rules restores file, finding filter, and review=next', async ({page}) => {
  await isolatedDevLogin(page)
  await page.getByTestId('source-upload').setInputFiles(uploadBuffer('alpha.xlsx', 'browser-alpha'))
  await page.waitForSelector('[data-testid="draft-items"]')
  await page.getByTestId('item-rule').first.selectOption(RULE_A)
  await page.getByTestId('source-upload').setInputFiles(uploadBuffer('beta.xlsx', 'browser-beta'))
  await page.waitForFunction(() => document.querySelector('[data-testid="draft-items"]')?.textContent?.includes('beta.xlsx'))
  await page.getByTestId('item-rule').last.selectOption(RULE_A)
  await page.waitForSelector('[data-testid="submit-audit"]:not([disabled])')
  await page.getByTestId('submit-audit').click()
  const roundId = await waitForRound(page)
  await page.waitForSelector('[data-testid="finding-status"]')
  await page.waitForFunction(() => document.body.innerText.includes('检查完成'))
  await page.waitForFunction(() => {
    const sel = document.querySelector('[data-testid="file-version-list"]') as HTMLSelectElement | null
    return Boolean(sel && sel.options.length >= 2)
  })
  const defaultFile = await page.getByTestId('file-version-list').evaluate((el: HTMLSelectElement) => el.options[el.selectedIndex].text)
  expect(defaultFile).toContain('alpha.xlsx')
  await expect(page.getByTestId('filter-all')).toHaveAttribute('aria-pressed', 'true')
  await page.getByTestId('file-version-list').selectOption({label: 'beta.xlsx'})
  await page.waitForFunction(() => (document.querySelector('[data-testid="file-version-list"]') as HTMLSelectElement | null)?.selectedOptions[0]?.text.includes('beta.xlsx'))
  await page.getByTestId('filter-PASS').click()
  await expect(page.getByTestId('filter-PASS')).toHaveAttribute('aria-pressed', 'true')
  const heading = await page.getByTestId('finding-heading').innerText()
  const findingKey = await page.getByTestId('finding-detail').getAttribute('data-finding-key')
  expect(findingKey).toBeTruthy()
  await page.getByTestId('context-link').click()
  await page.waitForURL('**/rules**')
  const returnLink = page.getByTestId('rule-return')
  await expect(returnLink).toBeVisible()
  await expect(returnLink).toHaveText('← 返回审核结果')
  await returnLink.click()
  await waitForRound(page)
  await page.waitForSelector('[data-testid="finding-status"]')
  const restoredFile = await page.getByTestId('file-version-list').evaluate((el: HTMLSelectElement) => el.options[el.selectedIndex].text)
  expect(restoredFile).toContain('beta.xlsx')
  await expect(page.getByTestId('filter-PASS')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('filter-all')).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByTestId('finding-detail')).toHaveAttribute('data-finding-key', findingKey!)
  await expect(page.getByTestId('finding-heading')).toHaveText(heading)
  await page.goto(`/?round=${roundId}&review=next`)
  await page.waitForSelector('[data-testid="finding-status"]')
  await expect(page.getByTestId('filter-unreviewed')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('filter-PASS')).toHaveAttribute('aria-pressed', 'false')
  const nextFile = await page.getByTestId('file-version-list').evaluate((el: HTMLSelectElement) => el.options[el.selectedIndex].text)
  const nextKey = await page.getByTestId('finding-detail').getAttribute('data-finding-key')
  expect(nextKey).toBeTruthy()
  expect(nextFile).toContain('xlsx')
})
