    def test_template_copy_requires_the_complete_zip_and_works_on_mobile(self):
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch()
            for scene, complete in [("templates-ready", True), ("templates-zip-incomplete", False)]:
                with self.subTest(scene=scene):
                    page = browser.new_page(viewport={"width": 390, "height": 844})
                    page.goto(PREVIEW + "/preview/audit.html?view=templates&scene=" + scene)
                    page.get_by_role("button", name="分享客户模板", exact=True).click()
                    dialog = page.get_by_role("dialog", name="分享客户模板", exact=True)
                    expect(dialog.get_by_role("list", name="本次分享的模板").get_by_role("listitem")).to_have_count(12)
                    dialog.get_by_role("tab", name="文件副本", exact=True).click()
                    expect(dialog.get_by_text("发送完整 ZIP 副本。后续修改权限不能收回已发送的副本。", exact=True)).to_be_visible()
                    dialog.get_by_role("checkbox", name="选择人员 示例李工", exact=True).check()
                    send = dialog.get_by_role("button", name="发送给 1 个目标", exact=True)
                    if complete:
                        expect(send).to_be_enabled()
                        send.click()
                        expect(dialog.get_by_role("listitem", name="发送到 示例李工", exact=True)).to_contain_text("已发送")
                        expect(dialog.get_by_text("本次发送：完整 ZIP 副本；后续撤权不能收回副本", exact=True)).to_be_visible()
                    else:
                        expect(dialog.get_by_text("模板包未就绪", exact=True)).to_be_visible()
                        expect(send).to_be_disabled()
                    self.assertLessEqual(page.evaluate("document.documentElement.scrollWidth"), 390)
                    page.close()
            browser.close()

