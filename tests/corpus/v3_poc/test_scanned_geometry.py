"""The real scanned corpus exercises geometry without paid model calls.

Owner tests use synthetic scans. Root corpus assets belong to this suite.
This does not replace the original V3 text and rule oracle.
"""

import asyncio
import re
from pathlib import Path

import cv2
import fitz
import numpy as np
from ppap_pdf_to_excel.vision import cell_ocr, page, raster


def test_real_dense_control_plan_pages_have_complete_physical_cell_partitions(monkeypatch):
    source = Path(__file__).resolve().parents[3] / "assets/poc测试/POC测试样本/Blanc Spoiler-有特殊特性清单/19-BLANC尾-生产控制计划.pdf"
    original = source.read_bytes()
    calls = []

    async def read_ids(**kwargs):
        schema = kwargs["response_schema"]["name"]
        calls.append(schema)
        if schema == "ppap_raster_cell_evidence":
            ids = [int(value) for value in re.findall(r"\d+", kwargs["prompt"].split("Requested CELL IDs: ", 1)[1])]
            assert 0 < len(ids) <= 32
            return {"cells": [{"id": index, "text": str(index)} for index in reversed(ids)]}
        assert schema == "ppap_scanned_page_remainder", "A dense physical grid must not be generated by the model"
        return {"paragraphs": [], "seals": [], "has_other_tables": False}

    monkeypatch.setattr(page, "call_llm_async", read_ids)
    monkeypatch.setattr(cell_ocr, "call_llm_async", read_ids)
    with fitz.open(stream=original, filetype="pdf") as pdf:
        for index, pdf_page in enumerate(pdf, 1):
            assert not pdf_page.get_text("words")
            image = page._render_page_image(pdf_page, scanned=True)
            original_width = max(info["width"] for info in pdf_page.get_image_info())
            assert abs(cv2.imdecode(np.frombuffer(image, dtype=np.uint8), 0).shape[1] - original_width) <= 1
            normalized, grids = raster.read_raster_page(image)
            assert len(grids) == 1
            grid = grids[0]
            occupied = set()
            rows = [["" for _ in range(grid.col_count)] for _ in range(grid.row_count)]
            height, width = cv2.imdecode(np.frombuffer(normalized, dtype=np.uint8), 0).shape
            for cell in grid.cells:
                x0, y0, x1, y1 = cell.bbox
                assert 0 <= x0 < x1 < width and 0 <= y0 < y1 < height
                slots = {(r, c) for r in range(cell.row, cell.end_row + 1) for c in range(cell.col, cell.end_col + 1)}
                assert slots and not occupied.intersection(slots)
                occupied.update(slots)
                rows[cell.row][cell.col] = str(cell.index)
            assert len(occupied) == grid.row_count * grid.col_count
            assert len(occupied) > 400
            expected = {
                "tables": [{"rows": rows, "merges": [dict(zip(("start_row", "start_col", "end_row", "end_col"), bounds, strict=True)) for bounds in grid.merges]}],
                "paragraphs": [],
                "seals": [],
            }
            page._validate_page(expected)
            calls.clear()
            actual = asyncio.run(page._read_page_async(normalized, index, len(pdf), [{"raster_grid": grid}]))
            assert actual == expected
            assert calls.count("ppap_raster_cell_evidence") == (len(grid.cells) + 31) // 32
            assert calls[-1] == "ppap_scanned_page_remainder"
    assert source.read_bytes() == original
